    [StructLayout(LayoutKind.Sequential, Pack = 1)]
    internal struct StudioModel
    {
        [MarshalAs(UnmanagedType.ByValArray, SizeConst = 64)]
        public byte[] _name;

        public readonly string Name
        {
            get
            {
                var end = Array.IndexOf(_name, (byte)0);
                return System.Text.Encoding.UTF8.GetString(_name, 0, end >= 0 ? end : _name.Length);
            }
        }

        public int Type;
        public float BoundingRadius;
        public int NumMeshes;
        public int MeshIndex;

        public int NumVertices;
        public int VertexIndex;
        public int TangentsIndex;

        public int NumAttachments;
        public int AttachmentIndex;

        public int NumEyeBalls;
        public int EyeBallIndex;

        public StudioModelVertexData VertexData;

        [MarshalAs(UnmanagedType.ByValArray, SizeConst = 32)]
        public byte[] _unused;
    }


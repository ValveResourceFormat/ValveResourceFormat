using System.Globalization;
using System.Text;
using System.Text.RegularExpressions;
using ValveKeyValue;
using ValveResourceFormat.IO;
using ValveResourceFormat.IO.Fgd;

var pathsToCheck = args ?? [];

if (pathsToCheck.Length < 1)
{
    Console.Error.WriteLine("Usage: ./program [path to Steam to find .fgd files in]");

    if (GameFolderLocator.SteamPath == null)
    {
        return 1;
    }

    Console.Error.WriteLine($"No path specified, searching Steam libraries.");

    pathsToCheck = [.. GameFolderLocator.FindAllSteamGames().Select(static x => x.SteamPath).ToHashSet()];
}

var allProperties = new HashSet<string>();
var entityMaterials = new Dictionary<string, string>();
var hammerClasses = new SortedDictionary<string, FgdClass>(StringComparer.Ordinal);
var gameInfos = new List<string>();

foreach (var arg in pathsToCheck)
{
    if (!Directory.Exists(arg))
    {
        Console.Error.WriteLine($"'{arg}' does not exist.");
        continue;
    }

    Console.WriteLine($"Searching {arg}");

    foreach (var file in Directory.EnumerateFiles(arg, "*.fgd", SearchOption.AllDirectories))
    {
        ParseFile(file);
    }

    // The classes every game shares are read as part of each game, with what the game changes of them
    gameInfos.AddRange(Directory.EnumerateFiles(arg, "gameinfo.gi", SearchOption.AllDirectories)
        .Where(static path => Path.GetFileName(Path.GetDirectoryName(path)) != "core"));
}

// A class several games declare is taken from the first, so the newest branch of the tools goes first
foreach (var gameInfo in gameInfos.OrderByDescending(static path => path.Contains("Counter-Strike Global Offensive", StringComparison.Ordinal)).ThenBy(static path => path, StringComparer.Ordinal))
{
    ParseGameClasses(gameInfo);
}

Console.WriteLine();

WriteClasses();
WriteProperties();
WriteMaterials();

return 0;

// The classes of one game as Hammer builds them
void ParseGameClasses(string gameInfo)
{
    using var fileLoader = new GameFileLoader(null, gameInfo);

    if (fileLoader.LoadFgd() is not { } fgd)
    {
        return;
    }

    var added = 0;

    foreach (var gameClass in fgd.Classes)
    {
        if (gameClass.Type != FgdClassType.BaseClass && hammerClasses.TryAdd(gameClass.Name.ToLowerInvariant(), gameClass))
        {
            added++;
        }
    }

    if (added > 0)
    {
        Console.WriteLine($"Found {added} new classes in {Path.GetDirectoryName(gameInfo)}");
    }
}

// The classes written back out as FGD, with nothing but what entities are drawn with. It is what
// a map is shown with where the tools of its game are not installed.
void WriteClasses()
{
    Console.WriteLine($"Found {hammerClasses.Count} classes");

    var str = new StringBuilder();

    str.Append("// <auto-generated/>\n// Use Misc/VrfFgdParser project\n");

    foreach (var gameClass in hammerClasses.Values)
    {
        str.Append(CultureInfo.InvariantCulture, $"\n@{gameClass.Type}");

        if (gameClass.HasColor)
        {
            str.Append(CultureInfo.InvariantCulture, $" color({gameClass.Color.R} {gameClass.Color.G} {gameClass.Color.B})");
        }

        if (gameClass.HasSize)
        {
            str.Append(CultureInfo.InvariantCulture, $" size({gameClass.Mins.X} {gameClass.Mins.Y} {gameClass.Mins.Z}, {gameClass.Maxs.X} {gameClass.Maxs.Y} {gameClass.Maxs.Z})");
        }

        foreach (var helper in gameClass.Helpers)
        {
            str.Append(' ');
            str.Append(helper.Name);

            if (helper.MetadataText != null)
            {
                str.Append(Regex.Replace(helper.MetadataText, @"\s+", " "));
            }
            else
            {
                str.Append(CultureInfo.InvariantCulture, $"({string.Join(", ", helper.Arguments.Select(QuoteText))})");
            }
        }

        if (GetText(gameClass.Metadata, "required_parent_class") is { Length: > 0 } requiredParentClass)
        {
            str.Append(CultureInfo.InvariantCulture, $" metadata{{ required_parent_class = {QuoteText(requiredParentClass)} }}");
        }

        str.Append(CultureInfo.InvariantCulture, $" = {gameClass.Name}\n[\n");

        // A variable of one of these types is drawn by a helper that is given its name
        foreach (var variable in gameClass.Variables)
        {
            var type = variable.DeclaredType switch
            {
                FgdVariableType.VecLine => "vecline",
                FgdVariableType.Axis => "axis",
                FgdVariableType.LocalAxis => "localaxis",
                _ => null,
            };

            if (type != null)
            {
                str.Append(CultureInfo.InvariantCulture, $"\t{variable.Name}({type})\n");
            }
        }

        str.Append("]\n");
    }

    File.WriteAllText("classes.fgd", str.ToString());
}

static string QuoteText(string value)
    => "\"" + value.Replace("\\", "\\\\", StringComparison.Ordinal).Replace("\"", "\\\"", StringComparison.Ordinal) + "\"";

// A key of a block of keys as text, or null when it is not there
static string? GetText(KVObject? keys, string key)
    => keys != null && keys.ContainsKey(key) ? keys[key].ToString(CultureInfo.InvariantCulture) : null;

// The property names and trigger materials of every Source 2 game, whichever game declares them
void ParseFile(string file)
{
    var directory = Path.GetDirectoryName(file)!;
    var isSource2 = File.Exists(Path.Join(directory, "gameinfo.gi"));

    Console.WriteLine();
    Console.ForegroundColor = isSource2 ? ConsoleColor.Green : ConsoleColor.Blue;
    Console.Write("Parsing ");
    Console.Write(file);
    Console.WriteLine(isSource2 ? string.Empty : " (not Source 2)");
    Console.ResetColor();

    if (!isSource2)
    {
        return;
    }

    // Each file is read on its own, opening what it includes through the game it is in
    using var fileLoader = new GameFileLoader(null, file);
    var fgd = new ForgeGameData(fileLoader.GetFileStream);

    fgd.Load(file);

    foreach (var error in fgd.Errors)
    {
        Console.WriteLine($"{Path.GetFileName(error.FileName)}({error.Line}): {error.Message}");
    }

    foreach (var gameClass in fgd.Classes)
    {
        foreach (var variable in gameClass.Variables)
        {
            allProperties.Add(variable.Name.ToLowerInvariant());
        }

        if (GetText(gameClass.Metadata, "auto_apply_material") is { } material && material != "materials/tools/toolstrigger.vmat")
        {
            entityMaterials[gameClass.Name] = material;
        }
    }
}

void WriteProperties()
{
    Console.WriteLine($"Found {allProperties.Count} unique properties");

    var propertiesString = new StringBuilder();

    foreach (var property in allProperties.OrderBy(x => x))
    {
        propertiesString.Append('"');
        propertiesString.Append(property);
        propertiesString.Append('"');
        propertiesString.Append(',');
        propertiesString.AppendLine();
    }

    File.WriteAllText("properties.txt", propertiesString.ToString());
}

void WriteMaterials()
{
    Console.WriteLine($"Found {entityMaterials.Count} entity materials");

    var str = new StringBuilder();

    foreach (var (name, material) in entityMaterials.OrderBy(x => x.Key))
    {
        str.AppendLine(CultureInfo.InvariantCulture, $"\"{name}\" => \"{material}\"");
    }

    File.WriteAllText("entity_materials.txt", str.ToString());
}
